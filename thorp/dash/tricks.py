"""The tricks of the trade, on the route to quantum physics (2026-11-07, Justin).

A trick is what a model can do, judged from outside by what it bets; a star is the mechanism inside
that does it (DECISIONS.md, "Tricks and stars"). The tricks are grouped into the seven WAYPOINTS a
model passes on the way to quantum physics: reading, knowing, counting, reasoning, mathematics,
physics, discovery. A waypoint's GATE tricks are the ones a model must perform before it moves on to
the next waypoint; the rest are milestones within it.

Each entry: what it does; its waypoint and whether it is a gate; the tricks it rests on
(`rests_on`, keys here); the size of model the field shows it at (`field_at` in words,
`field_params` a rough number for the size band and the target, None where the field has not shown
it); how sure that size is (`sure`: "documented" in a model of that size; "rough", an
order-of-magnitude reading of the papers; "today", a reading of where today's models stand, which
has moved down as training data improved); the models and source; the kinds of head thought to do
it (`stars`, keys of `heads.KNOWN_HEADS`); Thorp's measurement (`fleet`, a key of
`thorp.fleet.TRICKS`) or how it could be measured; and `goal_class`, the class of ship expected to
reach it, by class name ("keel", "pilot", "speller", "stylist", "paragraph", "bettor", "summit"),
or None when it is beyond the ladder. `taught` marks a trick the field shows only in models trained
on that task, not on books: a reference point, never a class's goal.

A class's goals are the tricks whose goal_class is that class; its target level is the highest
waypoint among them, and its ceiling the goals at that waypoint: the upper limit of what that size of
ship is expected to do before the next class takes over. The goal classes follow "an order of
magnitude smaller than the field" where the field's size allows, and the depth a trick needs.
"""

